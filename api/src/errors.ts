  CURRENT_CALLING_EXISTS:'CURRENT_CALLING_EXISTS', RECOVERY_NOT_ALLOWED:'RECOVERY_NOT_ALLOWED',
  EMERGENCY_CALL_NOT_ALLOWED:'EMERGENCY_CALL_NOT_ALLOWED',
