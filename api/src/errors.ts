  QUEUE_NOT_FOUND:'QUEUE_NOT_FOUND', SCENE_NOT_FOUND:'SCENE_NOT_FOUND',
  DISPLAY_NOT_FOUND:'DISPLAY_NOT_FOUND', VALIDATION_ERROR:'VALIDATION_ERROR',
  CAPACITY_FULL:'CAPACITY_FULL', RESERVATION_NOT_ALLOWED:'RESERVATION_NOT_ALLOWED',
  TIME_SLOT_OVERLAP:'TIME_SLOT_OVERLAP', INVALID_TIME_RANGE:'INVALID_TIME_RANGE',
  SCENE_CONFIG_INVALID:'SCENE_CONFIG_INVALID', INVALID_STATE:'INVALID_STATE',
  ALREADY_ACCEPTED:'ALREADY_ACCEPTED', EXPIRED:'EXPIRED',
